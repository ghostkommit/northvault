"""Embed the pinned, local QR encoder as a Swift constant; no network/build plugins."""
from pathlib import Path

root = Path(__file__).resolve().parent.parent
source = root / "vendor/qrcode-terminal/QRCode"
js = ['(function () {', 'var factories = Object.create(null), cache = Object.create(null);']
for path in sorted(source.glob('*.js')):
    js += [f'factories["./{path.stem}"] = function(module, exports, require) {{', path.read_text(), '};']
js += ['''function require(name) {
    if (!cache[name]) {
        if (!factories[name]) throw new Error("Unknown QR module");
        var module = { exports: {} };
        cache[name] = module;
        factories[name](module, module.exports, require);
    }
    return cache[name].exports;
}
return function(bytes, level) {
    var QRCode = require("./index");
    var qr = new QRCode(-1, [1, 0, 3, 2][level]);
    qr.addData(String.fromCharCode.apply(null, bytes));
    qr.make();
    return qr.modules;
};
})()''']
script = '\n'.join(js)
assert '"""#' not in script
output = root / 'vendor/EFQRCode/Sources/EFQRCode/QRMatrixScript.swift'
output.write_text('// Generated by scripts/bundle-qr-encoder.py. Do not edit.\n'
                  '// QRCode for JavaScript: Copyright (c) 2009 Kazuhiko Arase (MIT).\n'
                  '// See vendor/qrcode-terminal for provenance and license.\n'
                  'let qrMatrixScript = #"""\n' + script + '\n"""#\n')
